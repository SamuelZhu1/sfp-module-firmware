#!/usr/bin/env python3
"""Generate SFF-8472 EEPROM images for the host tests (fixtures.h).

These are synthetic images laid out byte for byte like a typical 10GBASE-LR
module's A0h/A2h pages, with valid CC_BASE, CC_EXT and CC_DMI checksums.
Replace or extend them with real dumps (`raw a0 0 128` / `ethtool -m <if> raw on
hex on`) once modules are on the bench; see docs/bringup.md.
"""
import struct
import sys


def put_str(page, off, length, text):
    b = text.encode("ascii").ljust(length, b" ")
    page[off:off + length] = b


def be16(page, off, value, signed=False):
    page[off:off + 2] = struct.pack(">h" if signed else ">H", value)


def checksums_a0(a0):
    a0[63] = sum(a0[0:63]) & 0xFF
    a0[95] = sum(a0[64:95]) & 0xFF


def make_a0(vendor, part, serial, wavelength, compliance, diag_type, bitrate=0x67):
    a0 = bytearray(256)
    a0[0] = 0x03          # SFP / SFP+
    a0[1] = 0x04          # extended identifier
    a0[2] = 0x07          # LC connector
    a0[3] = compliance    # 10G Ethernet compliance bits
    a0[11] = 0x06         # 64B/66B encoding
    a0[12] = bitrate      # nominal rate, 100 Mb/s units (0x67 = 10.3 Gb/s)
    a0[14] = 10           # length, km
    put_str(a0, 20, 16, vendor)
    a0[37:40] = b"\x00\x90\x65"  # vendor OUI
    put_str(a0, 40, 16, part)
    put_str(a0, 56, 4, "A")
    be16(a0, 60, wavelength)
    a0[65] = 0x1A         # options: TX_DISABLE, TX_FAULT, RX_LOS implemented
    put_str(a0, 68, 16, serial)
    put_str(a0, 84, 8, "220314  ")
    a0[92] = diag_type
    a0[93] = 0xF0
    a0[94] = 0x08         # SFF-8472 rev 12.x
    checksums_a0(a0)
    return a0


def make_a2(live, thresholds, ext=None):
    a2 = bytearray(256)
    off = 0
    for signed, values in thresholds:
        for v in values:
            be16(a2, off, v, signed)
            off += 2
    if ext:
        for i, f in enumerate(ext["rx_pwr"]):
            a2[56 + 4 * i:60 + 4 * i] = struct.pack(">f", f)
        o = 76
        for name in ("bias", "tx", "temp", "vcc"):
            be16(a2, o, ext[name][0])
            be16(a2, o + 2, ext[name][1], signed=True)
            o += 4
    a2[95] = sum(a2[0:95]) & 0xFF   # CC_DMI
    temp, vcc, bias, tx, rx = live
    be16(a2, 96, temp, signed=True)
    be16(a2, 98, vcc)
    be16(a2, 100, bias)
    be16(a2, 102, tx)
    be16(a2, 104, rx)
    return a2


LR_THRESHOLDS = [
    (True, [78 * 256, -13 * 256, 73 * 256, -8 * 256]),   # temp, 1/256 degC
    (False, [37000, 29000, 36000, 30000]),                # vcc, 100 uV
    (False, [6600, 1000, 6000, 1500]),                    # bias, 2 uA
    (False, [11220, 1513, 8913, 1905]),                   # tx power, 0.1 uW (+0.5/-8.2, -0.5/-7.2 dBm)
    (False, [12589, 100, 10000, 126]),                    # rx power, 0.1 uW (+1/-20, 0/-19 dBm)
]

FIXTURES = {
    # 10GBASE-LR, internally calibrated, DDM present
    "lr": (make_a0("FINISAR CORP.", "FTLX1471D3BCL", "UZ80TQ2", 1310, 0x20, 0x68),
           make_a2((int(35.5 * 256), 33000, 3400, 5754, 3090), LR_THRESHOLDS)),
    # 10GBASE-SR, externally calibrated: tx slope 1.5, rx = 2 * raw + 10
    "sr_ext": (make_a0("ACME OPTICS", "SR-10G-EXT", "EXT0001", 850, 0x10, 0x50),
               make_a2((int(40.0 * 256), 33100, 3000, 4000, 1000), LR_THRESHOLDS,
                       ext={"rx_pwr": [0.0, 0.0, 0.0, 2.0, 10.0],
                            "bias": (0x0100, 0), "tx": (0x0180, 0),
                            "temp": (0x0100, -256), "vcc": (0x0100, 0)})),
    # passive copper-like part with no diagnostics
    "noddm": (make_a0("GENERIC", "DAC-1M", "DAC0001", 0, 0x00, 0x00),
              bytearray(256)),
}


def c_array(name, data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return f"static const uint8_t {name}[256] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    out = ["// Generated by gen_fixtures.py. Do not edit by hand.",
           "#ifndef SFP_FIXTURES_H", "#define SFP_FIXTURES_H", "#include <stdint.h>", ""]
    for key, (a0, a2) in FIXTURES.items():
        out.append(c_array(f"fx_{key}_a0", a0))
        out.append(c_array(f"fx_{key}_a2", a2))
    out.append("#endif")
    path = sys.argv[1] if len(sys.argv) > 1 else "fixtures.h"
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
